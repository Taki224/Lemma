from __future__ import annotations

import asyncio
import contextlib
import os
import resource
import shutil
import signal
import subprocess
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from app.config import AppSettings

SandboxMode = Literal["bwrap", "uid_rlimit"]

_BWRAP_PROBE_CACHE: bool | None = None

_EXCLUDED_PROJECT_DIRS = {".git", ".build", ".texmf", "paper-reviews", "__pycache__"}
_EXCLUDED_PROJECT_FILES = {"secrets.yaml", ".DS_Store", ".latexmkrc", "latexmkrc"}
_ARTIFACT_EXTENSIONS = {
    ".pdf",
    ".gz",
    ".synctex",
    ".log",
    ".fls",
    ".aux",
    ".bbl",
    ".blg",
    ".out",
    ".toc",
    ".fdb_latexmk",
    ".bcf",
    ".run.xml",
}


@dataclass(slots=True)
class SandboxResult:
    returncode: int
    stdout: str
    stderr: str
    timed_out: bool
    sandbox_mode: SandboxMode
    duration_ms: int


def _extra_tex_paths() -> list[str]:
    candidates = [
        "/usr/local/texlive/bin",
        "/Library/TeX/texbin",
        "/usr/local/texlive/bin/x86_64-linux",
        "/usr/local/texlive/bin/aarch64-linux",
        "/usr/local/texlive/bin/universal-darwin",
    ]
    for texlive_dir in sorted(Path("/usr/local/texlive").glob("20*/bin/*"), reverse=True) if Path("/usr/local/texlive").is_dir() else []:
        candidates.insert(0, str(texlive_dir))
    return [p for p in candidates if Path(p).is_dir()]


def _build_safe_path_env() -> str:
    base_parts = ["/usr/local/bin", "/usr/bin", "/bin"]
    tex_parts = _extra_tex_paths()
    all_parts: list[str] = []
    for part in [*tex_parts, *base_parts]:
        if part not in all_parts:
            all_parts.append(part)
    return ":".join(all_parts)


def _bwrap_readonly_mounts() -> list[str]:
    args: list[str] = [
        "--unshare-pid",
        "--unshare-ipc",
        "--unshare-uts",
        "--new-session",
        "--die-with-parent",
        "--dir",
        "/tmp",
        "--tmpfs",
        "/tmp",
        "--dir",
        "/etc",
        "--dir",
        "/data",
        "--ro-bind",
        "/usr",
        "/usr",
        "--ro-bind",
        "/bin",
        "/bin",
        "--ro-bind",
        "/lib",
        "/lib",
    ]
    optional_dirs = [
        "/lib64",
        "/etc/alternatives",
        "/etc/texmf",
        "/var/lib/texmf",
        "/usr/local/texlive",
    ]
    for opt in optional_dirs:
        if Path(opt).exists():
            args.extend(["--ro-bind", opt, opt])
    args.extend(["--dev", "/dev", "--proc", "/proc"])
    return args


def probe_bwrap_support(force_reprobe: bool = False) -> bool:
    """Probe whether bwrap --unshare-net works in the current kernel/container environment."""
    global _BWRAP_PROBE_CACHE
    if _BWRAP_PROBE_CACHE is not None and not force_reprobe:
        return _BWRAP_PROBE_CACHE

    bwrap_bin = shutil.which("bwrap")
    if not bwrap_bin:
        _BWRAP_PROBE_CACHE = False
        return False

    cmd = [bwrap_bin, "--unshare-net", *_bwrap_readonly_mounts(), "--", "true"]
    try:
        proc = subprocess.run(
            cmd,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=5.0,
            check=False,
        )
        _BWRAP_PROBE_CACHE = proc.returncode == 0
    except (OSError, subprocess.SubprocessError):
        _BWRAP_PROBE_CACHE = False

    return _BWRAP_PROBE_CACHE


def generate_hardened_texmf_cnf(
    build_dir: Path,
    project_texmf_dir: Path,
    global_texmf_dir: Path,
    isolated_texmf: bool = False,
) -> Path:
    """Write a hardened texmf.cnf blocking shell_escape and arbitrary path I/O."""
    build_dir = Path(build_dir)
    build_dir.mkdir(parents=True, exist_ok=True)
    cnf_path = build_dir / "texmf.cnf"

    if isolated_texmf:
        texmfhome_val = ""
    else:
        texmfhome_val = f"{{{project_texmf_dir},{global_texmf_dir}}}"

    lines = [
        "% Hardened texmf.cnf generated by Lemma",
        "shell_escape = f",
        "shell_escape_commands =",
        "enable_pipes = f",
        "openin_any = p",
        "openout_any = p",
        f"TEXMFHOME = {texmfhome_val}",
        "",
    ]
    cnf_path.write_text("\n".join(lines), encoding="utf-8")
    return cnf_path


def build_sanitized_tex_env(
    cnf_dir: Path,
    project_texmf_dir: Path,
    global_texmf_dir: Path,
    isolated_texmf: bool = False,
) -> dict[str, str]:
    """Construct a scrubbed environment for sandboxed TeX subprocesses."""
    texmfhome = "" if isolated_texmf else f"{{{project_texmf_dir},{global_texmf_dir}}}"
    return {
        "PATH": _build_safe_path_env(),
        "HOME": str(cnf_dir),
        "LANG": "C.UTF-8",
        "LC_ALL": "C.UTF-8",
        "TEXMFCNF": f"{cnf_dir}:",
        "TEXMFHOME": texmfhome,
        "max_print_line": "1000",
        "error_line": "254",
        "half_error_line": "238",
    }


def _validate_no_external_symlinks(root_dir: Path) -> None:
    resolved_root = root_dir.resolve()
    for dirpath, dirnames, filenames in os.walk(root_dir, followlinks=False):
        current_dir = Path(dirpath)
        filtered_dirs: list[str] = []
        for dname in dirnames:
            if dname in _EXCLUDED_PROJECT_DIRS:
                continue
            dpath = current_dir / dname
            if dpath.is_symlink():
                target = dpath.resolve()
                if not target.is_relative_to(resolved_root):
                    raise PermissionError(
                        f"External directory symlink rejected in compile staging: {dpath} -> {target}"
                    )
            filtered_dirs.append(dname)
        dirnames[:] = filtered_dirs

        for fname in filenames:
            if fname in _EXCLUDED_PROJECT_FILES:
                continue
            fpath = current_dir / fname
            if fpath.is_symlink():
                target = fpath.resolve()
                if not target.is_relative_to(resolved_root):
                    raise PermissionError(
                        f"External file symlink rejected in compile staging: {fpath} -> {target}"
                    )


def stage_compile_workspace(
    project_dir: Path,
    build_dir: Path,
    staging_dir: Path,
) -> None:
    """Copy project source files and warm .aux/.bbl artifacts into an isolated staging directory."""
    project_dir = Path(project_dir)
    build_dir = Path(build_dir)
    staging_dir = Path(staging_dir)

    _validate_no_external_symlinks(project_dir)

    staging_dir.mkdir(parents=True, exist_ok=True)
    os.chmod(staging_dir, 0o700)

    resolved_project = project_dir.resolve()
    for dirpath, dirnames, filenames in os.walk(project_dir, followlinks=False):
        current_dir = Path(dirpath)
        dirnames[:] = [d for d in dirnames if d not in _EXCLUDED_PROJECT_DIRS]
        rel_dir = current_dir.resolve().relative_to(resolved_project)
        dest_dir = staging_dir / rel_dir
        dest_dir.mkdir(parents=True, exist_ok=True)

        for fname in filenames:
            if fname in _EXCLUDED_PROJECT_FILES:
                continue
            src_file = current_dir / fname
            resolved_src = src_file.resolve()
            if not resolved_src.is_relative_to(resolved_project):
                raise PermissionError(
                    f"Path escapes project root during compile staging: {src_file}"
                )
            shutil.copy2(resolved_src, dest_dir / fname)

    if build_dir.is_dir():
        resolved_build = build_dir.resolve()
        for dirpath, _, filenames in os.walk(build_dir, followlinks=False):
            current_dir = Path(dirpath)
            rel_dir = current_dir.resolve().relative_to(resolved_build)
            dest_dir = staging_dir / rel_dir
            for fname in filenames:
                if fname.endswith((".aux", ".bbl")):
                    src_artifact = current_dir / fname
                    if not src_artifact.is_symlink():
                        dest_dir.mkdir(parents=True, exist_ok=True)
                        shutil.copy2(src_artifact, dest_dir / fname)


def _harvest_build_artifacts(staging_dir: Path, build_dir: Path) -> None:
    build_dir.mkdir(parents=True, exist_ok=True)
    resolved_staging = staging_dir.resolve()
    for dirpath, _, filenames in os.walk(staging_dir, followlinks=False):
        current_dir = Path(dirpath)
        rel_dir = current_dir.resolve().relative_to(resolved_staging)
        dest_dir = build_dir / rel_dir
        for fname in filenames:
            if fname == "texmf.cnf":
                continue
            is_synctex = fname.endswith(".synctex.gz") or fname.endswith(".synctex")
            ext = Path(fname).suffix.lower()
            if is_synctex or ext in _ARTIFACT_EXTENSIONS:
                src_file = current_dir / fname
                if src_file.is_file() and not src_file.is_symlink():
                    dest_dir.mkdir(parents=True, exist_ok=True)
                    dest_file = dest_dir / fname
                    if dest_file.is_symlink():
                        dest_file.unlink(missing_ok=True)
                    shutil.copy2(src_file, dest_file)


def _make_preexec_fn(timeout_sec: int, memory_limit_mb: int):
    cpu_limit = max(1, int(timeout_sec) + 2)
    mem_bytes = int(memory_limit_mb) * 1024 * 1024

    def _preexec() -> None:
        os.setsid()
        try:
            resource.setrlimit(resource.RLIMIT_CPU, (cpu_limit, cpu_limit))
        except (ValueError, OSError):
            pass
        try:
            resource.setrlimit(resource.RLIMIT_AS, (mem_bytes, mem_bytes))
        except (ValueError, OSError):
            # macOS Darwin disallows lowering RLIMIT_AS below dyld shared cache region
            pass

    return _preexec


def _wrap_command(
    inner_cmd: list[str],
    staging_dir: Path,
    project_texmf_dir: Path,
    global_texmf_dir: Path,
    isolated_texmf: bool,
    use_bwrap: bool,
    timeout_sec: int,
    memory_limit_mb: int,
) -> list[str]:
    cmd = list(inner_cmd)
    if use_bwrap:
        bwrap_bin = shutil.which("bwrap") or "bwrap"
        bwrap_args = [
            bwrap_bin,
            "--unshare-net",
            *_bwrap_readonly_mounts(),
        ]
        if not isolated_texmf:
            if global_texmf_dir.is_dir():
                bwrap_args.extend(["--ro-bind", str(global_texmf_dir), str(global_texmf_dir)])
            if project_texmf_dir.is_dir():
                bwrap_args.extend(["--ro-bind", str(project_texmf_dir), str(project_texmf_dir)])
        bwrap_args.extend(
            [
                "--bind",
                str(staging_dir),
                "/work",
                "--chdir",
                "/work",
                "--",
                *cmd,
            ]
        )
        cmd = bwrap_args

    wrapper_bin = Path("/usr/local/bin/run-as-texrunner")
    if wrapper_bin.is_file() and os.access(wrapper_bin, os.X_OK):
        for dirpath, _, filenames in os.walk(staging_dir):
            try:
                os.chmod(dirpath, 0o777)
            except OSError:
                pass
            for fn in filenames:
                try:
                    os.chmod(os.path.join(dirpath, fn), 0o666)
                except OSError:
                    pass
        cmd = [str(wrapper_bin), *cmd]

    return cmd


async def _exec_step(
    cmd: list[str],
    cwd: Path,
    env: dict[str, str],
    remaining_timeout: float,
    memory_limit_mb: int,
) -> tuple[int, str, str, bool]:
    proc = await asyncio.create_subprocess_exec(
        *cmd,
        cwd=str(cwd),
        env=env,
        stdin=asyncio.subprocess.DEVNULL,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
        preexec_fn=_make_preexec_fn(max(1, int(remaining_timeout)), memory_limit_mb),
    )
    try:
        stdout_bytes, stderr_bytes = await asyncio.wait_for(
            proc.communicate(),
            timeout=max(0.1, remaining_timeout),
        )
        return (
            proc.returncode if proc.returncode is not None else 1,
            stdout_bytes.decode("utf-8", errors="replace"),
            stderr_bytes.decode("utf-8", errors="replace"),
            False,
        )
    except asyncio.TimeoutError:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except (ProcessLookupError, PermissionError, OSError):
            pass
        try:
            proc.kill()
        except (ProcessLookupError, PermissionError, OSError):
            pass
        try:
            stdout_bytes, stderr_bytes = await asyncio.wait_for(proc.communicate(), timeout=1.0)
        except (asyncio.TimeoutError, OSError):
            stdout_bytes, stderr_bytes = b"", b""
        return (
            -9,
            stdout_bytes.decode("utf-8", errors="replace"),
            stderr_bytes.decode("utf-8", errors="replace"),
            True,
        )


async def run_sandboxed_tex(
    project_dir: Path,
    build_dir: Path,
    root_tex: str,
    settings: AppSettings,
    isolated_texmf: bool = False,
) -> SandboxResult:
    """Execute LaTeX compilation inside an isolated staging workspace with hardened texmf.cnf."""
    if not root_tex or root_tex.startswith("-") or ".." in root_tex:
        raise ValueError(f"Invalid root_tex filename: {root_tex!r}")
    start_ns = time.monotonic_ns()
    project_dir = Path(project_dir).resolve()
    build_dir = Path(build_dir).resolve()
    project_texmf_dir = project_dir / ".texmf"
    global_texmf_dir = settings.texmf_dir.resolve()

    use_bwrap = probe_bwrap_support()
    sandbox_mode: SandboxMode = "bwrap" if use_bwrap else "uid_rlimit"

    generate_hardened_texmf_cnf(
        build_dir=build_dir,
        project_texmf_dir=project_texmf_dir,
        global_texmf_dir=global_texmf_dir,
        isolated_texmf=isolated_texmf,
    )

    with contextlib.ExitStack() as cleanup_stack:
        tmp_stage = tempfile.mkdtemp(prefix="lemma_tex_stage_")
        cleanup_stack.callback(shutil.rmtree, tmp_stage, ignore_errors=True)
        staging_dir = Path(tmp_stage).resolve()
        stage_compile_workspace(
            project_dir=project_dir,
            build_dir=build_dir,
            staging_dir=staging_dir,
        )
        cnf_dir_in_proc = Path("/work") if use_bwrap else staging_dir
        generate_hardened_texmf_cnf(
            build_dir=staging_dir,
            project_texmf_dir=project_texmf_dir,
            global_texmf_dir=global_texmf_dir,
            isolated_texmf=isolated_texmf,
        )
        env = build_sanitized_tex_env(
            cnf_dir=cnf_dir_in_proc,
            project_texmf_dir=project_texmf_dir,
            global_texmf_dir=global_texmf_dir,
            isolated_texmf=isolated_texmf,
        )

        safe_path = env["PATH"]
        latexmk_bin = shutil.which("latexmk", path=safe_path)
        pdflatex_bin = shutil.which("pdflatex", path=safe_path) or "pdflatex"
        bibtex_bin = shutil.which("bibtex", path=safe_path)

        stem = Path(root_tex).stem
        had_warm_bbl = (staging_dir / f"{stem}.bbl").is_file()
        had_warm_aux = (staging_dir / f"{stem}.aux").is_file()

        deadline = time.monotonic() + float(settings.compile_timeout_seconds)
        stdout_parts: list[str] = []
        stderr_parts: list[str] = []
        timed_out = False
        returncode = 0

        if latexmk_bin:
            inner = [
                latexmk_bin,
                "-norc",
                "-pdf",
                f"-pdflatex={pdflatex_bin} -no-shell-escape %O %S",
                "-synctex=1",
                "-recorder",
                "-interaction=nonstopmode",
                "-file-line-error",
                root_tex,
            ]
            cmd = _wrap_command(
                inner_cmd=inner,
                staging_dir=staging_dir,
                project_texmf_dir=project_texmf_dir,
                global_texmf_dir=global_texmf_dir,
                isolated_texmf=isolated_texmf,
                use_bwrap=use_bwrap,
                timeout_sec=settings.compile_timeout_seconds,
                memory_limit_mb=settings.compile_memory_limit_mb,
            )
            returncode, out, err, timed_out = await _exec_step(
                cmd=cmd,
                cwd=staging_dir,
                env=env,
                remaining_timeout=deadline - time.monotonic(),
                memory_limit_mb=settings.compile_memory_limit_mb,
            )
            stdout_parts.append(out)
            stderr_parts.append(err)
        else:
            pdflatex_inner = [
                pdflatex_bin,
                "-no-shell-escape",
                "-synctex=1",
                "-recorder",
                "-interaction=nonstopmode",
                "-file-line-error",
                root_tex,
            ]
            pdflatex_cmd = _wrap_command(
                inner_cmd=pdflatex_inner,
                staging_dir=staging_dir,
                project_texmf_dir=project_texmf_dir,
                global_texmf_dir=global_texmf_dir,
                isolated_texmf=isolated_texmf,
                use_bwrap=use_bwrap,
                timeout_sec=settings.compile_timeout_seconds,
                memory_limit_mb=settings.compile_memory_limit_mb,
            )
            returncode, out, err, timed_out = await _exec_step(
                cmd=pdflatex_cmd,
                cwd=staging_dir,
                env=env,
                remaining_timeout=deadline - time.monotonic(),
                memory_limit_mb=settings.compile_memory_limit_mb,
            )
            stdout_parts.append(out)
            stderr_parts.append(err)

            if not timed_out and returncode == 0:
                aux_path = staging_dir / f"{stem}.aux"
                log_path = staging_dir / f"{stem}.log"
                aux_text = aux_path.read_text(encoding="utf-8", errors="ignore") if aux_path.is_file() else ""
                log_text = log_path.read_text(encoding="utf-8", errors="ignore") if log_path.is_file() else ""

                needs_bibtex = (
                    bibtex_bin is not None
                    and "\\bibdata{" in aux_text
                    and (not had_warm_bbl or "Citation `" in log_text or "No file " + stem + ".bbl" in log_text)
                )
                if needs_bibtex and bibtex_bin is not None:
                    bib_cmd = _wrap_command(
                        inner_cmd=[bibtex_bin, stem],
                        staging_dir=staging_dir,
                        project_texmf_dir=project_texmf_dir,
                        global_texmf_dir=global_texmf_dir,
                        isolated_texmf=isolated_texmf,
                        use_bwrap=use_bwrap,
                        timeout_sec=settings.compile_timeout_seconds,
                        memory_limit_mb=settings.compile_memory_limit_mb,
                    )
                    _, b_out, b_err, timed_out = await _exec_step(
                        cmd=bib_cmd,
                        cwd=staging_dir,
                        env=env,
                        remaining_timeout=deadline - time.monotonic(),
                        memory_limit_mb=settings.compile_memory_limit_mb,
                    )
                    stdout_parts.append(b_out)
                    stderr_parts.append(b_err)

                    for _ in range(2):
                        if timed_out or time.monotonic() >= deadline:
                            break
                        returncode, out2, err2, timed_out = await _exec_step(
                            cmd=pdflatex_cmd,
                            cwd=staging_dir,
                            env=env,
                            remaining_timeout=deadline - time.monotonic(),
                            memory_limit_mb=settings.compile_memory_limit_mb,
                        )
                        stdout_parts.append(out2)
                        stderr_parts.append(err2)
                elif not had_warm_aux and "Rerun to get cross-references right" in log_text:
                    returncode, out2, err2, timed_out = await _exec_step(
                        cmd=pdflatex_cmd,
                        cwd=staging_dir,
                        env=env,
                        remaining_timeout=deadline - time.monotonic(),
                        memory_limit_mb=settings.compile_memory_limit_mb,
                    )
                    stdout_parts.append(out2)
                    stderr_parts.append(err2)

        _harvest_build_artifacts(staging_dir=staging_dir, build_dir=build_dir)

    duration_ms = max(1, int((time.monotonic_ns() - start_ns) / 1_000_000))
    return SandboxResult(
        returncode=returncode,
        stdout="\n".join(p for p in stdout_parts if p),
        stderr="\n".join(p for p in stderr_parts if p),
        timed_out=timed_out,
        sandbox_mode=sandbox_mode,
        duration_ms=duration_ms,
    )
