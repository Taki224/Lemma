from __future__ import annotations

import re
from collections import OrderedDict
from typing import Sequence

from app.integrity.audit_log import AuditLogEntry

DISCLOSURE_FILENAME = "ai_disclosure.tex"

_DOC_CLASS_RE = re.compile(
    r"^[ \t]*\\documentclass(?:\[[^\]]*\])?\{([^}]+)\}",
    re.MULTILINE,
)
_CHAPTER_CLASSES = frozenset({"book", "report", "memoir", "scrbook", "scrreprt"})

_LATEX_SPECIAL_CHARS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "[": r"{[}",
    "]": r"{]}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
_LATEX_ESCAPE_RE = re.compile(
    "|".join(re.escape(k) for k in _LATEX_SPECIAL_CHARS.keys())
)


def escape_latex(text: str) -> str:
    """Escape plain text for safe inclusion inside LaTeX prose or table cells."""
    if not text:
        return ""
    normalized = " ".join(text.split())
    return _LATEX_ESCAPE_RE.sub(lambda m: _LATEX_SPECIAL_CHARS[m.group(0)], normalized)


def _humanize_category(category: str) -> str:
    if not category:
        return "AI-assisted revision"
    return category.replace("_", " ").strip().capitalize()


def _heading_command(root_tex_content: str) -> str:
    match = _DOC_CLASS_RE.search(root_tex_content or "")
    if match:
        doc_class = match.group(1).strip().lower()
        if doc_class in _CHAPTER_CLASSES:
            return r"\chapter*"
    return r"\section*"


def _provider_label(provider: str) -> str:
    p = (provider or "").strip().lower()
    if p == "local":
        return "Local"
    if p == "openrouter":
        return "OpenRouter"
    if p == "manual":
        return "External"
    return provider or "External"


def render_disclosure_latex(
    entries: Sequence[AuditLogEntry],
    *,
    root_tex_content: str = "",
) -> str:
    """Render a standalone, publication-ready LaTeX AI Usage Disclosure section."""
    heading_cmd = _heading_command(root_tex_content)

    lines: list[str] = [
        "% BEGIN LEMMA-AI-DISCLOSURE",
        "% Generated by Lemma Academic Integrity Mode from .ai-audit-log.json",
        "% Include this file in your manuscript where appropriate, e.g. \\input{ai_disclosure}",
        f"{heading_cmd}{{Declaration of Generative AI and AI-Assisted Technologies}}",
        "",
        (
            "During the preparation of this work, the author(s) used generative AI and "
            "AI-assisted technologies in accordance with institutional guidelines and the "
            "European Commission's \\textit{Living Guidelines on the Responsible Use of "
            "Generative AI in Research}. After using these tools, the author(s) critically "
            "reviewed, verified against primary sources, and edited the content as needed, "
            "and take full responsibility for the content of this publication."
        ),
        "",
    ]

    if not entries:
        lines.extend(
            [
                (
                    "No substantive generative AI assistance has been logged for this "
                    "project yet."
                ),
                "% END LEMMA-AI-DISCLOSURE",
                "",
            ]
        )
        return "\n".join(lines)

    # Group entries by (model_id, provider, purpose) for a clean, readable table
    grouped: OrderedDict[tuple[str, str, str], dict[str, object]] = OrderedDict()
    for entry in entries:
        purpose_label = entry.purpose or _humanize_category(entry.category)
        key = (
            entry.model_id or "unspecified",
            entry.provider or "openrouter",
            purpose_label,
        )
        bucket = grouped.get(key)
        if bucket is None:
            bucket = {
                "display_name": entry.model_display_name or entry.model_id or "Unspecified model",
                "model_id": entry.model_id,
                "provider": entry.provider,
                "purpose": purpose_label,
                "files": [],
                "sections": [],
                "verified_count": 0,
                "total_count": 0,
                "notes": [],
            }
            grouped[key] = bucket

        bucket["total_count"] = int(bucket["total_count"]) + 1  # type: ignore[arg-type]
        if entry.human_verified:
            bucket["verified_count"] = int(bucket["verified_count"]) + 1  # type: ignore[arg-type]

        files_list: list[str] = bucket["files"]  # type: ignore[assignment]
        for f in entry.affected_files:
            if f and f not in files_list:
                files_list.append(f)

        sections_list: list[str] = bucket["sections"]  # type: ignore[assignment]
        if entry.section_hint and entry.section_hint not in sections_list:
            sections_list.append(entry.section_hint)

        notes_list: list[str] = bucket["notes"]  # type: ignore[assignment]
        if entry.verification_note and entry.verification_note not in notes_list:
            notes_list.append(entry.verification_note)

    lines.extend(
        [
            r"\begin{table}[htbp]",
            r"\centering",
            r"\caption{Summary of Generative AI Tool Usage and Human Verification}",
            r"\label{tab:ai-disclosure}",
            r"\begin{tabular}{p{0.26\linewidth} p{0.28\linewidth} p{0.24\linewidth} p{0.16\linewidth}}",
            r"\hline",
            r"\textbf{Tool / Model} & \textbf{Purpose \& Scope} & \textbf{Affected Files / Sections} & \textbf{Verification} \\",
            r"\hline",
        ]
    )

    for bucket in grouped.values():
        display_name = escape_latex(str(bucket["display_name"]))
        model_id = str(bucket["model_id"])
        prov = escape_latex(_provider_label(str(bucket["provider"])))
        if model_id and model_id != bucket["display_name"]:
            tool_cell = f"{display_name} (\\texttt{{{escape_latex(model_id)}}}, {prov})"
        else:
            tool_cell = f"{display_name} ({prov})"

        purpose_cell = escape_latex(str(bucket["purpose"]))

        files_list = bucket["files"]  # type: ignore[assignment]
        sections_list = bucket["sections"]  # type: ignore[assignment]
        scope_parts: list[str] = []
        if files_list:
            scope_parts.append(
                ", ".join(f"\\texttt{{{escape_latex(f)}}}" for f in files_list)
            )
        if sections_list:
            scope_parts.append(
                "(" + "; ".join(escape_latex(s) for s in sections_list) + ")"
            )
        scope_cell = " ".join(scope_parts) if scope_parts else "Manuscript"

        verified_count = int(bucket["verified_count"])  # type: ignore[arg-type]
        total_count = int(bucket["total_count"])  # type: ignore[arg-type]
        notes_list = bucket["notes"]  # type: ignore[assignment]
        if verified_count == total_count:
            verif_cell = "Verified by author"
        elif verified_count > 0:
            verif_cell = f"Partially verified ({verified_count}/{total_count})"
        else:
            verif_cell = "Pending author review"
        if notes_list:
            verif_cell += f": {escape_latex('; '.join(notes_list[:2]))}"

        lines.append(f"{tool_cell} & {purpose_cell} & {scope_cell} & {verif_cell} \\\\")

    lines.extend(
        [
            r"\hline",
            r"\end{tabular}",
            r"\end{table}",
            "% END LEMMA-AI-DISCLOSURE",
            "",
        ]
    )
    return "\n".join(lines)
